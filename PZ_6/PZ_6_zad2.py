#Дан список размера N. Найти номера тех элементов списка, которые больше своего
#правого соседа, и количество таких элементов. Найденные номера выводить в
#порядке их возрастания.

import random
while True:
    try:
        n = int(input("Введите размер списка n (больше 1): "))
        if n > 1:
            break
        print("ошибка. размер должен быть больше 1")
    except ValueError:
        print("Введите целое число!")
a = []
for _ in range(n):
    a.append(random.randint(0, 99))
print("Исходный список:", a)
count = 0
print("номера элементов, которые больше правого соседа:", end='')
for k in range(n - 1):
    if a[k] > a[k + 1]:
        print(k, end=' ')
        count += 1
print("Количество таких элементов:", count)