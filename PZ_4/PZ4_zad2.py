#на прямоугольнике. Операции умножения и деления не использовать.
a = input("Введите А: ")
while True:
    try:
        a = int(a)
        if a > 0:
            break
        else:
            print("ошибка. число должно быть больше нуля")
    except ValueError:
        print("ошибка. нужно ввести целое число: ")
    a = input("Введите число А заново: ")
b = input("Введите В: ")
